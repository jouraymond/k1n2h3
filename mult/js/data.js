/* ---------- 口訣（十十乘法，含 10、1、0） ---------- */
const CN = ["","一","二","三","四","五","六","七","八","九"];
function cnNum(n){
  if(n === 0) return "零";
  if(n < 10) return CN[n];
  if(n === 10) return "一十";
  const t = Math.floor(n/10), o = n%10;
  return (t === 1 ? "十" : CN[t] + "十") + (o ? CN[o] : "");
}
function kouJue(a,b){
  const lo = Math.min(a,b), hi = Math.max(a,b), p = a*b;
  if(lo === 0 || hi === 10) return a + " × " + b + " = " + p;
  return CN[lo] + CN[hi] + (p < 10 ? "得" : "") + cnNum(p);
}

/* ---------- 小工具 ---------- */
const rnd = (a,b) => a + Math.floor(Math.random()*(b-a+1));
const pickOne = a => a[Math.floor(Math.random()*a.length)];
function shuffle(a){
  for(let i=a.length-1;i>0;i--){const j=rnd(0,i);const t=a[i];a[i]=a[j];a[j]=t;}
  return a;
}
